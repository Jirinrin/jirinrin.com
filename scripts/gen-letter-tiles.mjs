// Regenerates the vertically-mirrored parchment tiles that the "letter" popup
// in the landscape repeats down its length (see the
// `.popup-window--letter::before` block in src/components/Landscape.scss):
//
//   src/assets/box-light-small.png (500x500)  ->  box-light-mirror-tile.png (500x1000)
//   src/assets/box-dark-small.png  (500x500)  ->  box-dark-mirror-tile.png  (500x1000)
//
// Each output is the source texture followed by a vertically flipped copy of
// itself, so a `repeat-y` background meets its own mirror image at every join
// instead of a hard wrap from the bottom edge back to the top one.
//
// Why this script exists (the tiles were previously generated ad hoc): the
// committed tiles were mirrored *with the source's alpha channel intact*, and
// the source art's outermost pixel rows are antialiased - their alpha averages
// ~242/255 rather than 255. The mirror duplicates exactly those rows at both
// joins (bottom row meets its own copy in the middle; top row meets the next
// tile's top row at the wrap), so every seam was a 2px band of ~5% see-through
// through which the dark landscape behind the popup showed as a faint grey
// line. Flattening the tiles to fully opaque (see removeAlpha below) removes
// the cause: the texture is opaque everywhere else anyway (mean alpha 254.9),
// and the ::before that uses it has its own `opacity: 0.85`, so the layer's
// intended translucency is unaffected.
//
// Run with: node scripts/gen-letter-tiles.mjs
// Idempotent-ish in the same spirit as scripts/optimize-assets.mjs: an output
// whose mtime is already >= its source's is skipped, so repeat runs are no-ops
// until the source art changes (pass --force to regenerate regardless).
import { stat } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = path.resolve(import.meta.dirname, '..');
const src = (...p) => path.resolve(ROOT, 'src/assets', ...p);
const FORCE = process.argv.includes('--force');

// The light tile has always been a touch lighter and lower-contrast than
// box-light-small.png itself - a deliberate "parchment lift" baked into the
// tile back when it was generated by hand, and the letter's look depends on
// it, so it's reproduced here rather than dropped. `a * input + b` fitted by
// least squares against the committed tile: mean error 0.6/255, max 2/255
// (the original was evidently applied at higher precision, hence not exact -
// but the residual is far below anything visible on a grainy paper texture
// shown at opacity 0.85 under the color-grade filter). The dark tile needs no
// such lift: it is box-dark-small.png verbatim (verified pixel for pixel).
const LIGHT_LIFT = { a: 0.654, b: 90.7 };

// Builds the mirrored tile: `base` on top, `base` flipped vertically below it.
// Done on raw RGB rather than with sharp's composite so the flip is an exact
// row-order reversal with no resampling anywhere near the joins.
async function mirrorTile(srcPath, outPath, lift) {
  let pipeline = sharp(srcPath);
  if (lift) pipeline = pipeline.linear(lift.a, lift.b);
  // removeAlpha() after the tone lift: it drops the channel outright (sharp
  // keeps colour un-premultiplied, so the RGB values are untouched), which is
  // what makes every row - the antialiased edge rows included - fully opaque.
  const { data, info } = await pipeline.removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width, height, channels } = info; // 500 x 500 x 3 (RGB)
  const stride = width * channels;

  const out = Buffer.alloc(stride * height * 2);
  data.copy(out, 0);
  for (let y = 0; y < height; y++) {
    data.copy(out, stride * (height + y), stride * (height - 1 - y), stride * (height - y));
  }

  await sharp(out, { raw: { width, height: height * 2, channels } })
    .png({ compressionLevel: 9 })
    .toFile(outPath);

  // The SCSS puts a matching `background-color` under the texture as a second
  // line of defence (a sub-pixel rounding gap between repeats would otherwise
  // show the backdrop through the same way the alpha seam did). Printing the
  // mean grey of the two rows that land on a join keeps those hard-coded
  // colours honest: re-check them here if the source art ever changes.
  const meanGrey = (y) => {
    let sum = 0;
    for (let x = 0; x < width; x++) sum += out[y * stride + x * channels];
    return Math.round(sum / width);
  };
  const seam = Math.round((meanGrey(0) + meanGrey(height - 1)) / 2);
  console.log(
    `[gen-letter-tiles] ${path.relative(ROOT, outPath)}: ${width}x${height * 2}, opaque, ` +
      `seam rows mean grey ${meanGrey(0)} / ${meanGrey(height - 1)} -> background-color rgb(${seam}, ${seam}, ${seam})`
  );
}

async function generate(srcName, outName, lift) {
  const srcPath = src(srcName);
  const outPath = src(outName);
  const [srcStat, outStat] = await Promise.all([
    stat(srcPath).catch(() => null),
    stat(outPath).catch(() => null),
  ]);
  if (!srcStat) {
    console.warn(`[gen-letter-tiles] missing source: ${path.relative(ROOT, srcPath)}`);
    return;
  }
  if (!FORCE && outStat && outStat.mtimeMs >= srcStat.mtimeMs) {
    console.log(`[gen-letter-tiles] up to date, skipped: ${path.relative(ROOT, outPath)}`);
    return;
  }
  await mirrorTile(srcPath, outPath, lift);
}

await generate('box-light-small.png', 'box-light-mirror-tile.png', LIGHT_LIFT);
await generate('box-dark-small.png', 'box-dark-mirror-tile.png', null);
